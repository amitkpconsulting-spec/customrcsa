/**
 * Helper to fetch milestones for a domain or combine for All
 */
export function getMilestonesForDomain(domain: RCSADomainType): DomainMilestone[] {
  if (domain === 'All') {
    // Collect from all domains, sorted chronologically by targetDate
    const all = [
      ...DEFAULT_DOMAIN_MILESTONES.Privacy,
      ...DEFAULT_DOMAIN_MILESTONES['Information Security'],
      ...DEFAULT_DOMAIN_MILESTONES.Cybersecurity,
      ...DEFAULT_DOMAIN_MILESTONES.Governance,
    ];
    return all.sort((a, b) => new Date(a.targetDate).getTime() - new Date(b.targetDate).getTime());
  }

  // Check if it's a combined domain like "Privacy + Information Security"
  if (domain.includes('+') || domain.includes('&')) {
    const parts = domain.split(/[+&]/).map((p) => p.trim());
    const matched: DomainMilestone[] = [];
    parts.forEach((part) => {
      const list = DEFAULT_DOMAIN_MILESTONES[part] || [];
      matched.push(...list);
    });
    if (matched.length > 0) {
      return matched.sort((a, b) => new Date(a.targetDate).getTime() - new Date(b.targetDate).getTime());
    }
  }

  const direct = DEFAULT_DOMAIN_MILESTONES[domain];
  if (direct) {
    return [...direct].sort((a, b) => new Date(a.targetDate).getTime() - new Date(b.targetDate).getTime());
  }

  // Default fallback to Governance / All
  return [...DEFAULT_DOMAIN_MILESTONES.Governance];
}

/**
 * Calculate renewal metrics summary
 */
export interface DomainRenewalSummary {
  nearestRenewalMilestone: DomainMilestone | null;
  daysUntilNextRenewal: number;
  totalRenewalEventsCount: number;
  activeCycleCompletionPct: number;
  criticalPathCount: number;
  overdueCount: number;
  nextAuditDateStr: string;
}

export function computeRenewalSummary(milestones: DomainMilestone[]): DomainRenewalSummary {
  const renewalItems = milestones.filter((m) => m.isRenewalDate || m.category === 'RENEWAL_EXPIRATION');
  const sortedRenewals = [...renewalItems].sort(
    (a, b) => new Date(a.targetDate).getTime() - new Date(b.targetDate).getTime()
  );
  
  const nearest = sortedRenewals.length > 0 ? sortedRenewals[0] : milestones[milestones.length - 1] || null;
  const daysUntil = nearest ? nearest.daysRemaining : 0;
  
  const totalProgress = milestones.reduce((sum, m) => sum + m.progressPct, 0);
  const avgProgress = milestones.length > 0 ? Math.round(totalProgress / milestones.length) : 0;
  
  const criticalCount = milestones.filter((m) => m.criticality === 'CRITICAL' || m.status === 'CRITICAL_PATH').length;
  const overdueCount = milestones.filter((m) => m.daysRemaining < 0 || m.status === 'OVERDUE').length;

  return {
    nearestRenewalMilestone: nearest,
    daysUntilNextRenewal: daysUntil,
    totalRenewalEventsCount: renewalItems.length,
    activeCycleCompletionPct: avgProgress,
    criticalPathCount: criticalCount,
    overdueCount,
    nextAuditDateStr: nearest ? nearest.targetDate : '2026-12-31',
  };
}
